// Bridges a small, explicit API into the sandboxed renderer (contextIsolation on, no nodeIntegration).
const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('mg', {
  getState: () => ipcRenderer.invoke('getState'),
  setLanguage: (language) => ipcRenderer.invoke('setLanguage', language),
  activatePublic: (code) => ipcRenderer.invoke('activatePublic', code),
  getPayment: () => ipcRenderer.invoke('getPayment'),
  walletStatus: () => ipcRenderer.invoke('walletStatus'),
  walletCreate: (passphrase) => ipcRenderer.invoke('walletCreate', passphrase),
  walletExport: () => ipcRenderer.invoke('walletExport'),
  channelOpen: (depositAtoms) => ipcRenderer.invoke('channelOpen', depositAtoms),
  channelPay: () => ipcRenderer.invoke('channelPay'),
  channelClose: () => ipcRenderer.invoke('channelClose'),
  channelRefund: () => ipcRenderer.invoke('channelRefund'),
  swapBuy: (method, atoms) => ipcRenderer.invoke('swapBuy', method, atoms),
  swapList: () => ipcRenderer.invoke('swapList'),
  swapRefund: (file, address) => ipcRenderer.invoke('swapRefund', file, address),
  openLightning: (invoice) => ipcRenderer.invoke('openLightning', invoice),
  getLog: () => ipcRenderer.invoke('getLog'),
  getConfig: () => ipcRenderer.invoke('getConfig'),
  saveConfig: (cfg) => ipcRenderer.invoke('saveConfig', cfg),
  setPeerPolicy: (policy) => ipcRenderer.invoke('setPeerPolicy', policy),
  genPsk: () => ipcRenderer.invoke('genPsk'),
  startClient: () => ipcRenderer.invoke('startClient'),
  stopClient: () => ipcRenderer.invoke('stopClient'),
  vpnOn: () => ipcRenderer.invoke('vpnOn'),
  vpnOff: () => ipcRenderer.invoke('vpnOff'),
  connect: () => ipcRenderer.invoke('connect'),
  disconnect: () => ipcRenderer.invoke('disconnect'),
  openConfigDir: () => ipcRenderer.invoke('openConfigDir'),
  openLogs: () => ipcRenderer.invoke('openLogs'),
  getLogPath: () => ipcRenderer.invoke('getLogPath'),
  clearLog: () => ipcRenderer.invoke('clearLog'),
  onLog: (cb) => ipcRenderer.on('log', (_e, line) => cb(line)),
  onStatus: (cb) => ipcRenderer.on('status', (_e, s) => cb(s)),
})
