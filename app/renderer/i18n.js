  // English unless the user chose another supported language.
  function detect(saved) {
    return LANGUAGES.includes(saved) ? saved : 'en'
  }
  function setLanguage(language) {
    current = detect(language)
    return current
  }
  function language() {
    return current
  }
  function t(key, vars = {}) {
    const text = STRINGS[current][key] ?? STRINGS.en[key] ?? key
    return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] === undefined ? '' : String(vars[name])))
  }
  // Fills elements marked data-i18n (text) and data-i18n-<attribute> (placeholder, aria-label, title).
  function apply(doc) {
    doc.documentElement.lang = current
    for (const el of doc.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n)
    for (const attr of ['placeholder', 'aria-label', 'title'])
      for (const el of doc.querySelectorAll(`[data-i18n-${attr}]`)) el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`)))
  }
